interface AiadcField {
  sectionKey: string;
  sectionLabel: string;
  permission: string;
  pageKey?: string;
  collection?: string;
  area?: string;
  sectionCode?: string;
  path: string;
  type: string;
  control: FieldControl;
  required: boolean;
  editable: boolean;
  guarded?: boolean;
  note?: string;
}

interface AiadcSectionSummary {
  key: string;
  label: string;
  fieldCount: number;
  publishedCount: number;
}

interface AiadcFieldApiRecord extends Omit<AiadcField, 'type' | 'control'> {
  fieldType: string;
  controlType: FieldControl;
  draftValue?: string;
  publishedValue?: string;
  updatedAt?: string;
  publishedAt?: string;
  version?: number;
}

interface PagedFields {
  records: AiadcFieldApiRecord[];
  total: number;
}

