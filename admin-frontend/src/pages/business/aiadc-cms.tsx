const normalizeApiField = (field: AiadcFieldApiRecord): AiadcField => ({
  ...field,
  type: field.fieldType,
  control: field.controlType,
});

const renderControl = (control: FieldControl) => <Tag color={control.includes('switch') ? 'green' : control.includes('upload') ? 'blue' : 'default'}>{control}</Tag>;

const renderFieldEditor = (field: AiadcField) => {
  if (!field.editable) {
    return <Input disabled placeholder={field.path} />;
  }
  if (field.control === 'switch' || field.control === 'publish-switch') {
    return <Switch checkedChildren="on" unCheckedChildren="off" />;
  }
  if (field.control === 'textarea' || field.control === 'markdown-editor' || field.control === 'schema-driven-extra') {
    return <Input.TextArea rows={6} placeholder={field.path} />;
  }
  if (field.control === 'select' || field.control === 'segmented') {
    return (
      <Select
        placeholder={field.path}
        options={[
          { label: 'draft', value: 'draft' },
          { label: 'published', value: 'published' },
          { label: 'zh', value: 'zh' },
          { label: 'en', value: 'en' },
          { label: '_self', value: '_self' },
          { label: '_blank', value: '_blank' },
        ]}
      />
    );
  }
  return <Input placeholder={field.path} />;
};

const AiadcCmsPage = () => {
  const { actionPermission, responsive, searchConfig, buildToolbarButtons } = usePagePermissionActions();
  const [activeKey, setActiveKey] = useState(sections[0].key);
  const [editingField, setEditingField] = useState<AiadcField | null>(null);
  const [fieldForm] = Form.useForm<{ valueJson?: unknown }>();
  const [loading, setLoading] = useState(false);
  const [saving, setSaving] = useState(false);
  const [serverSections, setServerSections] = useState<AiadcSectionSummary[]>([]);
  const [serverFields, setServerFields] = useState<AiadcField[]>([]);
  const displayedSections = serverSections.length
    ? serverSections.map((section) => sections.find((item) => item.key === section.key) || {
        key: section.key,
        label: section.label,
        description: `${section.fieldCount} fields, ${section.publishedCount} published`,
        permissionPrefix: `aiadc:cms:${section.key}`,
        records: [],
      })
    : sections;
  const activeSection = displayedSections.find((section) => section.key === activeKey) || displayedSections[0] || sections[0];
  const allFields = serverFields.length ? serverFields : fields;
  const activeFields = useMemo(() => allFields.filter((field) => field.sectionKey === activeSection.key), [activeSection.key, allFields]);
  const totalEditableFields = allFields.filter((field) => field.editable).length;
  const guardedFields = allFields.filter((field) => field.guarded).length;

  const loadCmsFields = useCallback(async () => {
    setLoading(true);
    try {
      const [sectionResult, fieldResult] = await Promise.all([
        request<AiadcSectionSummary[]>('/v1/aiadc/cms/sections', {
          method: 'GET',
          ...API_OPTS.SILENT_NO_REDIRECT,
        }),
        request<PagedFields>('/v1/aiadc/cms/fields', {
          method: 'GET',
          params: { pageNo: 1, pageSize: 200 },
          ...API_OPTS.SILENT_NO_REDIRECT,
        }),
      ]);
      setServerSections(sectionResult);
      setServerFields((fieldResult.records || []).map(normalizeApiField));
      if (!sectionResult.some((section) => section.key === activeKey) && sectionResult[0]) {
        setActiveKey(sectionResult[0].key);
      }
    } catch (error) {
      setServerSections([]);
      setServerFields([]);
      showErrorMessage(error, t('AIADC CMS 后端暂不可用，已切换到本地字段契约', 'AIADC CMS backend is unavailable. Using the local field contract.'));
    } finally {
      setLoading(false);
    }
  }, [activeKey]);

  useEffect(() => {
    void loadCmsFields();
  }, [loadCmsFields]);

  const openEditor = useCallback(
    (field: AiadcField) => {
      setEditingField(field);
      const apiField = field as AiadcField & { draftValue?: string; publishedValue?: string };
      fieldForm.setFieldsValue({ valueJson: apiField.draftValue ?? apiField.publishedValue ?? '' });
    },
    [fieldForm],
  );

  const saveEditingField = useCallback(async () => {
    if (!editingField) {
      return;
    }
    setSaving(true);
    try {
      const values = await fieldForm.validateFields();
      await request<AiadcFieldApiRecord>('/v1/aiadc/cms/fields', {
        method: 'PUT',
        data: {
          sectionKey: editingField.sectionKey,
          pageKey: editingField.pageKey,
          collectionKey: editingField.collection,
          areaKey: editingField.area,
          sectionCode: editingField.sectionCode,
          fieldPath: editingField.path,
          valueJson: typeof values.valueJson === 'string' ? values.valueJson : JSON.stringify(values.valueJson ?? null),
        },
        ...API_OPTS.NO_REDIRECT,
      });
      message.success(t('字段草稿已保存', 'Field draft saved'));
      setEditingField(null);
      await loadCmsFields();
    } finally {
      setSaving(false);
    }
  }, [editingField, fieldForm, loadCmsFields]);

  const publishEditingField = useCallback(async () => {
    const id = (editingField as AiadcField & { id?: number } | null)?.id;
    if (!id) {
      message.warning(t('请先保存字段，再发布', 'Save the field before publishing'));
      return;
    }
    setSaving(true);
    try {
      await request<AiadcFieldApiRecord>(`/v1/aiadc/cms/fields/${id}/publish`, {
        method: 'POST',
        ...API_OPTS.NO_REDIRECT,
      });
      message.success(t('字段已发布', 'Field published'));
      setEditingField(null);
      await loadCmsFields();
    } finally {
      setSaving(false);
    }
  }, [editingField, loadCmsFields]);

  const columns = useMemo<ProColumns<AiadcField>[]>(
    () => [
      { title: t('板块', 'Section'), dataIndex: 'sectionLabel', hideInTable: true },
      { title: t('页面', 'Page'), dataIndex: 'pageKey', width: 110, renderText: (_, record) => record.pageKey || record.collection || '-' },
      { title: t('区域', 'Area'), dataIndex: 'sectionCode', width: 140, renderText: (_, record) => record.sectionCode || record.area || record.collection || '-' },
      { title: t('字段', 'Field'), dataIndex: 'path', ellipsis: true, render: (_, record) => <Typography.Text copyable={{ text: record.path }}>{record.path}</Typography.Text> },
      { title: t('类型', 'Type'), dataIndex: 'type', width: 160 },
      { title: t('控件', 'Control'), dataIndex: 'control', width: 180, render: (_, record) => renderControl(record.control) },
      { title: t('必填', 'Required'), dataIndex: 'required', width: 90, search: false, render: (_, record) => <Tag color={record.required ? 'red' : 'default'}>{record.required ? 'Yes' : 'No'}</Tag> },
      { title: t('可编辑', 'Editable'), dataIndex: 'editable', width: 90, search: false, render: (_, record) => <Tag color={record.editable ? 'green' : 'default'}>{record.editable ? 'Yes' : 'No'}</Tag> },
      {
        title: t('操作', 'Actions'),
        valueType: 'option',
        fixed: responsive.isDesktop ? 'right' : undefined,
        render: (_, record) => [
          <Button key="edit" type="link" size="small" icon={<EditOutlined />} disabled={!record.editable || !actionPermission.can(record.permission)} onClick={() => openEditor(record)}>
            {t('编辑', 'Edit')}
          </Button>,
        ],
      },
    ],
    [actionPermission, responsive.isDesktop],
  );

  return (
    <ManagementPage title={t('AIADC 内容中台', 'AIADC content management')} subTitle={t('独立业务系统字段契约', 'Independent business field contract')}>
      <ManagementPageBody>
        <Card>
          <Descriptions column={responsive.isMobile ? 1 : 4} size="small">
            <Descriptions.Item label={t('业务板块', 'Sections')}>{sections.length}</Descriptions.Item>
            <Descriptions.Item label={t('字段总数', 'Fields')}>{fields.length}</Descriptions.Item>
            <Descriptions.Item label={t('可编辑字段', 'Editable')}>{totalEditableFields}</Descriptions.Item>
            <Descriptions.Item label={t('受保护字段', 'Guarded')}>{guardedFields}</Descriptions.Item>
          </Descriptions>
          <Typography.Paragraph type="secondary" style={{ margin: '12px 0 0' }}>
            {t(
              '本页面按比赛宣传、比赛报名、活动、项目、新闻等板块组织 AIADC-WEB JSON 字段，写接口接入后可复用同一套表格、抽屉、权限和发布流程。',
              'This page groups the AIADC-WEB JSON fields by promotion, registration, activities, projects, news, and more. Backend APIs can reuse the same table, drawer, permission, and publish workflow.',
            )}
          </Typography.Paragraph>
        </Card>

        <Spin spinning={loading}>
        <Tabs
          activeKey={activeKey}
          onChange={setActiveKey}
          items={displayedSections.map((section) => ({
            key: section.key,
            label: section.label,
            children: (
              <Space direction="vertical" size="middle" style={{ width: '100%' }}>
                <Card size="small">
                  <Space direction="vertical" size={4}>
                    <Typography.Text strong>{section.description}</Typography.Text>
                    <Space wrap>
                      <Tag icon={<SafetyCertificateOutlined />} color={actionPermission.can(`${section.permissionPrefix}:update`) ? 'green' : 'orange'}>
                        {section.permissionPrefix}:update
                      </Tag>
                      <Tag>{section.records.length} records</Tag>
                      <Tag>{activeFields.length} fields</Tag>
                    </Space>
                  </Space>
                </Card>
                <ManagementTable<AiadcField>
                  rowKey={(record) => `${record.sectionKey}:${record.pageKey || record.collection}:${record.sectionCode || record.area}:${record.path}`}
                  columns={columns}
                  isMobile={responsive.isMobile}
                  search={searchConfig}
                  dataSource={activeFields}
                  pagination={{ pageSize: 12, showSizeChanger: true }}
                  toolBarRender={() =>
                    buildToolbarButtons([
                      { key: 'refresh', label: t('刷新', 'Refresh'), icon: <ReloadOutlined />, onClick: () => void loadCmsFields() },
                      { key: 'export', label: t('导出契约', 'Export contract'), icon: <ExportOutlined />, onClick: () => void navigator.clipboard?.writeText(JSON.stringify({ sections: displayedSections, fields: allFields }, null, 2)).then(() => message.success(t('契约 JSON 已复制', 'Contract JSON copied'))) },
                    ])
                  }
                />
              </Space>
            ),
          }))}
        />
        </Spin>
      </ManagementPageBody>

      <Drawer
        title={editingField ? `${t('编辑字段', 'Edit field')} ${editingField.path}` : t('编辑字段', 'Edit field')}
        open={Boolean(editingField)}
        onClose={() => setEditingField(null)}
        width={responsive.isMobile ? '100%' : 560}
        destroyOnHidden
        extra={
          <Button
            icon={<CopyOutlined />}
            onClick={() => void navigator.clipboard?.writeText(editingField?.path || '').then(() => message.success(t('字段路径已复制', 'Field path copied')))}
          >
            {t('复制路径', 'Copy path')}
          </Button>
        }
        footer={
          <Space>
            <Button onClick={() => setEditingField(null)}>{t('取消', 'Cancel')}</Button>
            <Button
              type="primary"
              loading={saving}
              disabled={!editingField || !actionPermission.can(editingField.permission)}
              onClick={() => void saveEditingField()}
            >
              {t('保存草稿', 'Save draft')}
            </Button>
            <Button loading={saving} disabled={!editingField || !actionPermission.can('aiadc:cms:publish')} onClick={() => void publishEditingField()}>
              {t('发布', 'Publish')}
            </Button>
          </Space>
        }
      >
        {editingField ? (
          <Form form={fieldForm} layout="vertical">
            <Descriptions column={1} size="small" bordered>
              <Descriptions.Item label={t('板块', 'Section')}>{editingField.sectionLabel}</Descriptions.Item>
              <Descriptions.Item label={t('位置', 'Location')}>{[editingField.pageKey || editingField.collection, editingField.sectionCode || editingField.area].filter(Boolean).join(' / ')}</Descriptions.Item>
              <Descriptions.Item label={t('字段类型', 'Type')}>{editingField.type}</Descriptions.Item>
              <Descriptions.Item label={t('权限', 'Permission')}>{editingField.permission}</Descriptions.Item>
            </Descriptions>
            <Form.Item name="valueJson" label={editingField.path} required={editingField.required} style={{ marginTop: 16 }}>
              {renderFieldEditor(editingField)}
            </Form.Item>
            {editingField.guarded ? (
              <Typography.Paragraph type="warning">
                {t('这是稳定业务键或路由标识，保存前应二次确认，避免影响前台读取。', 'This is a stable business key or route identifier. Confirm before saving because it affects public reads.')}
              </Typography.Paragraph>
            ) : null}
          </Form>
        ) : null}
      </Drawer>
    </ManagementPage>
  );
};

export default AiadcCmsPage;
